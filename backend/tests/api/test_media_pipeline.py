"""The ffmpeg path on synthetic media and AI-09/AI-10 through record-then-replay cassettes
(IMPLEMENTATION_PLAN.md §0.8 deferred pipeline tests).

Media are generated by ffmpeg from its built-in test sources (a colour pattern and a 440 Hz sine
tone): no real recording is used. The fake provider answers AI-09 and AI-10; a first run records
cassettes and a second run on a fresh database replays them with no provider at all, so the
replay path is exercised end to end. Requires ffmpeg and ffprobe (installed in CI).
"""

